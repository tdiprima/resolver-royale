#!/usr/bin/env bash
# dns-benchmark.sh — Cross-platform DNS benchmark (Mac / Ubuntu / RHEL)
# Ported from PowerShell. Requires: dig, bc
# Usage: ./dns-benchmark.sh [--apply] [--restore]

# ─── ANSI Colors ──────────────────────────────────────────────────────────────
RED='\033[0;31m';    LRED='\033[1;31m'
GREEN='\033[0;32m';  LGREEN='\033[1;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m';   LBLUE='\033[1;34m'
CYAN='\033[0;36m';   LCYAN='\033[1;36m'
MAGENTA='\033[0;35m';LMAGENTA='\033[1;35m'
WHITE='\033[1;37m'
GRAY='\033[0;37m'
BOLD='\033[1m'
DIM='\033[2m'
RESET='\033[0m'

# ─── DNS Server Database ───────────────────────────────────────────────────────
declare -A DNS_NAMES DNS_IPS DNS_PRIVACY DNS_DNSSEC

add_server() {
  local key="$1" name="$2" ip="$3" privacy="$4" dnssec="$5"
  DNS_NAMES[$key]="$name"
  DNS_IPS[$key]="$ip"
  DNS_PRIVACY[$key]="$privacy"
  DNS_DNSSEC[$key]="$dnssec"
}

add_server "cloudflare"      "Cloudflare"              "1.1.1.1"        "High"   "Yes"
add_server "cloudflare_sec"  "Cloudflare Security"     "1.1.1.2"        "High"   "Yes"
add_server "cloudflare_fam"  "Cloudflare Family"       "1.1.1.3"        "High"   "Yes"
add_server "google"          "Google"                   "8.8.8.8"        "Low"    "Yes"
add_server "google2"         "Google Secondary"         "8.8.4.4"        "Low"    "Yes"
add_server "quad9"           "Quad9"                    "9.9.9.9"        "High"   "Yes"
add_server "quad9_unsec"     "Quad9 Unsecured"          "9.9.9.10"       "Medium" "No"
add_server "opendns"         "OpenDNS"                  "208.67.222.222" "Medium" "No"
add_server "opendns2"        "OpenDNS Secondary"        "208.67.220.220" "Medium" "No"
add_server "opendns_fam"     "OpenDNS FamilyShield"     "208.67.222.123" "Medium" "No"
add_server "comodo"          "Comodo Secure"            "8.26.56.26"     "Medium" "No"
add_server "level3"          "Level3"                   "4.2.2.1"        "Low"    "No"
add_server "level3b"         "Level3 Secondary"         "4.2.2.2"        "Low"    "No"
add_server "norton"          "Norton ConnectSafe"       "199.85.126.10"  "Medium" "No"
add_server "adguard"         "AdGuard"                  "94.140.14.14"   "High"   "Yes"
add_server "adguard_fam"     "AdGuard Family"           "94.140.14.15"   "High"   "Yes"
