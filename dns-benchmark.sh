SERVER_KEYS=(cloudflare cloudflare_sec cloudflare_fam google google2 quad9
             quad9_unsec opendns opendns2 opendns_fam comodo level3 level3b
             norton adguard adguard_fam nextdns)

# Test domains — diverse, real-world mix
TEST_DOMAINS=(
  "google.com" "youtube.com" "github.com" "amazon.com" "microsoft.com"
  "cloudflare.com" "reddit.com" "netflix.com" "apple.com" "twitter.com"
)

ITERATIONS=5   # queries per domain per server
TIMEOUT=3      # seconds per dig query

# ─── OS Detection ─────────────────────────────────────────────────────────────
detect_os() {
  if [[ "$OSTYPE" == "darwin"* ]]; then
    echo "mac"
  elif [[ -f /etc/os-release ]]; then
    source /etc/os-release
    case "${ID:-}" in
      ubuntu|debian) echo "ubuntu" ;;
      rhel|centos|fedora|rocky|almalinux) echo "rhel" ;;
      *) echo "linux" ;;
    esac
  else
    echo "linux"
  fi
}

OS=$(detect_os)

# ─── Dependency Check ─────────────────────────────────────────────────────────
check_deps() {
  local missing=()
  for cmd in dig bc; do
    command -v "$cmd" &>/dev/null || missing+=("$cmd")
  done
  if [[ ${#missing[@]} -gt 0 ]]; then
    echo -e "${LRED}✗ Missing dependencies: ${missing[*]}${RESET}"
    echo ""
    case "$OS" in
      mac)    echo -e "${YELLOW}Install with: brew install bind${RESET}" ;;
      ubuntu) echo -e "${YELLOW}Install with: sudo apt install -y dnsutils bc${RESET}" ;;
      rhel)   echo -e "${YELLOW}Install with: sudo dnf install -y bind-utils bc${RESET}" ;;
    esac
    exit 1
  fi
}

# ─── Current DNS Detection ────────────────────────────────────────────────────
get_current_dns() {
  local dns_ip="" dns_source=""

  if [[ "$OS" == "mac" ]]; then
    # macOS: scutil --dns is authoritative; /etc/resolv.conf is generated from it
    dns_ip=$(scutil --dns 2>/dev/null \
      | awk '/nameserver/{print $3; exit}')
    dns_source="/etc/resolv.conf (generated by scutil/configd)"

    # Also show the actual resolv.conf line for reference
    local resolv_line
    resolv_line=$(grep -m1 '^nameserver' /etc/resolv.conf 2>/dev/null || true)
    [[ -z "$dns_ip" && -n "$resolv_line" ]] && dns_ip="${resolv_line#nameserver }"

  else
    # Linux: prefer systemd-resolved stub if active
    if systemctl is-active --quiet systemd-resolved 2>/dev/null; then
      dns_ip=$(resolvectl status 2>/dev/null \
        | awk '/DNS Servers:/{print $3; exit}')
      # The actual file used for lookups is the stub
      if [[ -f /run/systemd/resolve/resolv.conf ]]; then
        dns_source="/run/systemd/resolve/resolv.conf (systemd-resolved)"
      else
        dns_source="/etc/resolv.conf → stub: 127.0.0.53 (systemd-resolved)"
      fi
    fi

    # Fallback: plain resolv.conf
    if [[ -z "$dns_ip" ]]; then
      local resolv=""
      if [[ -f /etc/resolv.conf ]]; then
        resolv="/etc/resolv.conf"
      fi
      if [[ -n "$resolv" ]]; then
        dns_ip=$(awk '/^nameserver/{print $2; exit}' "$resolv" 2>/dev/null || true)
        dns_source="$resolv"
      fi
    fi

    # RHEL/NetworkManager fallback
    if [[ -z "$dns_ip" ]] && command -v nmcli &>/dev/null; then
      dns_ip=$(nmcli -t -f IP4.DNS device show 2>/dev/null \
        | awk -F: '/IP4.DNS/{print $2; exit}')
      dns_source="NetworkManager (nmcli)"
    fi
  fi

  CURRENT_DNS="${dns_ip:-unknown}"
  CURRENT_DNS_SOURCE="${dns_source:-unknown}"
}

# ─── Add Current DNS to Benchmark ─────────────────────────────────────────────
# Adds the user's current resolver as a competitor unless it already matches
# one of the known servers.
add_current_dns() {
  local current_ip="$1"
  if [[ -z "$current_ip" || "$current_ip" == "unknown" ]]; then
    return
  fi

  for key in "${SERVER_KEYS[@]}"; do
    if [[ "${DNS_IPS[$key]}" == "$current_ip" ]]; then
      return
    fi
  done

  add_server "current_dns" "Current DNS" "$current_ip" "Unknown" "Unknown"
  SERVER_KEYS=("current_dns" "${SERVER_KEYS[@]}")
}

# ─── Benchmark a Single Server ────────────────────────────────────────────────
# Outputs: avg_ms median_ms jitter_ms reliability_pct
benchmark_server() {
  local server_ip="$1"
  local -a times=()
  local success=0 fail=0

  for domain in "${TEST_DOMAINS[@]}"; do
    for (( i=0; i<ITERATIONS; i++ )); do
      local output
      output=$(dig @"$server_ip" "$domain" +time=$TIMEOUT +tries=1 +stats 2>/dev/null || true)
      local qt
      qt=$(echo "$output" | awk '/Query time:/{print $4}')
      if [[ -n "$qt" && "$qt" =~ ^[0-9]+$ ]]; then
        times+=("$qt")
        (( success++ ))
      else
        (( fail++ ))
      fi
    done
  done

  local total=$(( success + fail ))
  if [[ $total -eq 0 || $success -eq 0 ]]; then
    echo "9999 9999 9999 0"
    return
  fi

  # Sort times for median / jitter
  local sorted
  sorted=$(printf '%s\n' "${times[@]}" | sort -n)
  local count="${#times[@]}"

  # Average
  local sum=0
  for t in "${times[@]}"; do (( sum += t )); done
  local avg_ms
  avg_ms=$(echo "scale=1; $sum / $count" | bc)

  # Median
  local mid=$(( count / 2 ))
  local median_ms
  if (( count % 2 == 0 )); then
    local a b
    a=$(echo "$sorted" | sed -n "${mid}p")
    b=$(echo "$sorted" | sed -n "$(( mid + 1 ))p")
    median_ms=$(echo "scale=1; ($a + $b) / 2" | bc)
  else
    median_ms=$(echo "$sorted" | sed -n "$(( mid + 1 ))p")
  fi

  # Jitter = max - min
  local min_t max_t
  min_t=$(echo "$sorted" | head -1)
  max_t=$(echo "$sorted" | tail -1)
  local jitter_ms=$(( max_t - min_t ))

  # Reliability %
  local reliability
  reliability=$(echo "scale=1; $success * 100 / $total" | bc)

  echo "$avg_ms $median_ms $jitter_ms $reliability"
}

# ─── Composite Score (same weights as PowerShell) ─────────────────────────────
# avg=40%, median=25%, jitter=25%, reliability=10%
# Lower latency/jitter = better; higher reliability = better
# Score is 0–100 (higher = better)
composite_score() {
  local avg="$1" median="$2" jitter="$3" reliability="$4"
  # Invert latency: cap at 500ms → score 0..100
  local avg_score median_score jitter_score
  avg_score=$(echo    "scale=2; if ($avg    > 500) 0 else (1 - $avg    / 500) * 100" | bc)
  median_score=$(echo "scale=2; if ($median > 500) 0 else (1 - $median / 500) * 100" | bc)
  jitter_score=$(echo "scale=2; if ($jitter > 200) 0 else (1 - $jitter / 200) * 100" | bc)

  echo "scale=2; 0.40 * $avg_score + 0.25 * $median_score + 0.25 * $jitter_score + 0.10 * $reliability" | bc
}

# ─── Letter Grade ─────────────────────────────────────────────────────────────
letter_grade() {
  local score="$1"
  local s
  s=$(printf "%.0f" "$score")
  if   (( s >= 95 )); then echo "A+"
  elif (( s >= 90 )); then echo "A"
  elif (( s >= 85 )); then echo "A-"
  elif (( s >= 80 )); then echo "B+"
  elif (( s >= 75 )); then echo "B"
  elif (( s >= 70 )); then echo "B-"
  elif (( s >= 65 )); then echo "C+"
  elif (( s >= 60 )); then echo "C"
  elif (( s >= 55 )); then echo "C-"
  elif (( s >= 50 )); then echo "D"
  else echo "F"
  fi
}

# ─── Score Color ──────────────────────────────────────────────────────────────
score_color() {
  local score="$1"
  local s
  s=$(printf "%.0f" "$score")
  if   (( s >= 80 )); then echo "$LGREEN"
  elif (( s >= 60 )); then echo "$YELLOW"
  else echo "$LRED"
  fi
}

# ─── Progress Bar ─────────────────────────────────────────────────────────────
draw_progress() {
  local current="$1" total="$2" label="$3"
  local pct=$(( current * 100 / total ))
  local filled=$(( current * 30 / total ))
  local bar=""
  for (( i=0; i<filled; i++ ));   do bar+="█"; done
  for (( i=filled; i<30; i++ )); do bar+="░"; done
  printf "\r  ${CYAN}[${bar}]${RESET} ${WHITE}%3d%%${RESET}  ${DIM}%-30s${RESET}" "$pct" "$label"
}

# ─── Apply DNS (requires root) ────────────────────────────────────────────────
apply_dns() {
  local new_ip="$1"
  if [[ $EUID -ne 0 ]]; then
    echo -e "${LRED}✗ --apply requires root (sudo $0 --apply)${RESET}"
    exit 1
  fi
  case "$OS" in
    mac)
      local iface
      iface=$(networksetup -listallnetworkservices 2>/dev/null | grep -v "^\*" | head -1)
      networksetup -setdnsservers "$iface" "$new_ip"
      echo -e "${LGREEN}✓ DNS set to ${new_ip} on ${iface}${RESET}"
      ;;
    ubuntu|linux)
      if command -v nmcli &>/dev/null; then
        local con
        con=$(nmcli -t -f NAME con show --active | head -1)
        nmcli con mod "$con" ipv4.dns "$new_ip"
        nmcli con up "$con"
        echo -e "${LGREEN}✓ DNS set to ${new_ip} via NetworkManager${RESET}"
      else
        echo -e "${YELLOW}⚠ NetworkManager not found. Manually edit /etc/resolv.conf:${RESET}"
        echo -e "  ${BOLD}nameserver ${new_ip}${RESET}"
      fi
      ;;
    rhel)
      if command -v nmcli &>/dev/null; then
        local con
        con=$(nmcli -t -f NAME con show --active | head -1)
        nmcli con mod "$con" ipv4.dns "$new_ip" ipv4.ignore-auto-dns yes
        nmcli con up "$con"
        echo -e "${LGREEN}✓ DNS set to ${new_ip} via NetworkManager${RESET}"
      fi
      ;;
  esac
}

restore_dns() {
  if [[ $EUID -ne 0 ]]; then
    echo -e "${LRED}✗ --restore requires root${RESET}"
    exit 1
  fi
  case "$OS" in
    mac)
      local iface
      iface=$(networksetup -listallnetworkservices 2>/dev/null | grep -v "^\*" | head -1)
      networksetup -setdnsservers "$iface" "Empty"
      echo -e "${LGREEN}✓ DNS restored to DHCP defaults on ${iface}${RESET}"
      ;;
    ubuntu|rhel|linux)
      if command -v nmcli &>/dev/null; then
        local con
        con=$(nmcli -t -f NAME con show --active | head -1)
        nmcli con mod "$con" ipv4.dns "" ipv4.ignore-auto-dns no
        nmcli con up "$con"
        echo -e "${LGREEN}✓ DNS restored to DHCP defaults${RESET}"
      fi
      ;;
  esac
}

# ─── Banner ───────────────────────────────────────────────────────────────────
print_banner() {
  echo ""
  echo -e "${LCYAN}╔══════════════════════════════════════════════════════╗${RESET}"
  echo -e "${LCYAN}║${RESET}  ${BOLD}${WHITE}⚡  DNS Benchmark  —  Mac / Ubuntu / RHEL${RESET}           ${LCYAN}║${RESET}"
  echo -e "${LCYAN}╚══════════════════════════════════════════════════════╝${RESET}"
  echo ""
}

# ─── Results Table ────────────────────────────────────────────────────────────
print_results() {
  echo ""
  echo -e "${BOLD}${WHITE}  Rank  Name                      IP               Avg    Med    Jitter  Rel%   Score  Grade${RESET}"
  echo -e "${DIM}  ────  ────────────────────────  ───────────────  ─────  ─────  ──────  ─────  ─────  ─────${RESET}"

  local rank=1
  for entry in "${SORTED_RESULTS[@]}"; do
    IFS='|' read -r key score avg med jitter rel <<< "$entry"
    local name="${DNS_NAMES[$key]}"
    local ip="${DNS_IPS[$key]}"
    local grade
    grade=$(letter_grade "$score")
    local color
    color=$(score_color "$score")

    # Rank color
    local rcolor="$GRAY"
    [[ $rank -eq 1 ]] && rcolor="$YELLOW"
    [[ $rank -eq 2 ]] && rcolor="$WHITE"
    [[ $rank -eq 3 ]] && rcolor="$LRED"  # bronze

    # Unreachable
    if (( $(echo "$avg > 999" | bc -l) )); then
      printf "  ${rcolor}%4d${RESET}  %-26s  %-15s  ${LRED}%-5s  %-5s  %-6s  %-5s  %-5s  %-5s${RESET}\n" \
        "$rank" "$name" "$ip" "—" "—" "—" "—" "0.0" "F"
    else
      printf "  ${rcolor}%4d${RESET}  %-26s  %-15s  ${color}%-5s  %-5s  %-6s  %-5s  %-5s  %-5s${RESET}\n" \
        "$rank" "$name" "$ip" \
        "${avg}ms" "${med}ms" "${jitter}ms" "${rel}%" \
        "$(printf '%.1f' "$score")" "$grade"
    fi
    (( rank++ ))
  done
  echo ""
}

# ─── Winner Block ─────────────────────────────────────────────────────────────
print_winner() {
  local winner_entry="${SORTED_RESULTS[0]}"
  IFS='|' read -r key score avg med jitter rel <<< "$winner_entry"
  local name="${DNS_NAMES[$key]}"
  local ip="${DNS_IPS[$key]}"
  local privacy="${DNS_PRIVACY[$key]}"
  local dnssec="${DNS_DNSSEC[$key]}"
  local grade
  grade=$(letter_grade "$score")

  echo -e "${LGREEN}╔══════════════════════════════════════════════════════╗${RESET}"
  echo -e "${LGREEN}║${RESET}  ${BOLD}${YELLOW}🏆  Fastest DNS: ${name}${RESET}"
  echo -e "${LGREEN}║${RESET}     ${LBLUE}IP:${RESET}          ${WHITE}${ip}${RESET}"
  echo -e "${LGREEN}║${RESET}     ${LBLUE}Avg Latency:${RESET} ${WHITE}${avg} ms${RESET}"
  echo -e "${LGREEN}║${RESET}     ${LBLUE}Median:${RESET}      ${WHITE}${med} ms${RESET}"
  echo -e "${LGREEN}║${RESET}     ${LBLUE}Jitter:${RESET}      ${WHITE}${jitter} ms${RESET}"
  echo -e "${LGREEN}║${RESET}     ${LBLUE}Reliability:${RESET} ${WHITE}${rel}%${RESET}"
  echo -e "${LGREEN}║${RESET}     ${LBLUE}Privacy:${RESET}     ${WHITE}${privacy}${RESET}"
  echo -e "${LGREEN}║${RESET}     ${LBLUE}DNSSEC:${RESET}      ${WHITE}${dnssec}${RESET}"
  echo -e "${LGREEN}║${RESET}     ${LBLUE}Score:${RESET}       ${LGREEN}$(printf '%.1f' "$score") (${grade})${RESET}"
  echo -e "${LGREEN}╚══════════════════════════════════════════════════════╝${RESET}"
  echo ""

  if [[ "$key" == "current_dns" ]]; then
    echo -e "  ${LGREEN}Your current DNS is already the fastest — no changes needed.${RESET}"
    echo ""
  else
    echo -e "  ${BOLD}To apply this DNS (requires sudo):${RESET}"
    case "$OS" in
      mac)
        local iface
        iface=$(networksetup -listallnetworkservices 2>/dev/null | grep -v "^\*" | head -1 || echo "Wi-Fi")
        echo -e "    ${CYAN}sudo networksetup -setdnsservers \"${iface}\" ${ip}${RESET}"
        echo -e "  ${BOLD}To restore DHCP DNS:${RESET}"
        echo -e "    ${CYAN}sudo networksetup -setdnsservers \"${iface}\" Empty${RESET}"
        ;;
      ubuntu|linux)
        echo -e "    ${CYAN}sudo nmcli con mod \"\$(nmcli -t -f NAME con show --active | head -1)\" ipv4.dns ${ip}${RESET}"
        echo -e "    ${CYAN}sudo nmcli con up \"\$(nmcli -t -f NAME con show --active | head -1)\"${RESET}"
        echo -e "  ${BOLD}Or via /etc/resolv.conf (transient):${RESET}"
        echo -e "    ${CYAN}echo 'nameserver ${ip}' | sudo tee /etc/resolv.conf${RESET}"
        ;;
      rhel)
        echo -e "    ${CYAN}sudo nmcli con mod \"\$(nmcli -t -f NAME con show --active | head -1)\" ipv4.dns ${ip} ipv4.ignore-auto-dns yes${RESET}"
        echo -e "    ${CYAN}sudo nmcli con up \"\$(nmcli -t -f NAME con show --active | head -1)\"${RESET}"
        ;;
    esac
    echo ""
    echo -e "  ${DIM}Or re-run with: sudo $0 --apply${RESET}"
    echo ""
  fi
}

# ─── Main ─────────────────────────────────────────────────────────────────────
main() {
  check_deps
  print_banner

  # Handle --apply / --restore flags
  if [[ "${1:-}" == "--restore" ]]; then
    restore_dns
    exit 0
  fi

  # ── Current DNS ──────────────────────────────────────────────────────────────
  get_current_dns
  add_current_dns "$CURRENT_DNS"
  echo -e "  ${BOLD}Current DNS:${RESET}  ${LMAGENTA}${CURRENT_DNS}${RESET}"
  echo -e "  ${BOLD}Source file:${RESET}  ${DIM}${CURRENT_DNS_SOURCE}${RESET}"
  echo ""
  echo -e "  ${DIM}OS detected: ${OS} | Iterations: ${ITERATIONS}×${#TEST_DOMAINS[@]} queries/server | Timeout: ${TIMEOUT}s${RESET}"
  echo ""
  echo -e "  ${YELLOW}Benchmarking ${#SERVER_KEYS[@]} servers — this takes ~1–2 minutes …${RESET}"
  echo ""

  # ── Benchmark Loop ───────────────────────────────────────────────────────────
  declare -A RESULTS_RAW  # key → "avg|med|jitter|rel"
  local total="${#SERVER_KEYS[@]}"
  local done=0

  for key in "${SERVER_KEYS[@]}"; do
    (( done++ ))
    draw_progress "$done" "$total" "${DNS_NAMES[$key]}"
    read -r avg med jitter rel <<< "$(benchmark_server "${DNS_IPS[$key]}")"
    RESULTS_RAW[$key]="${avg}|${med}|${jitter}|${rel}"
  done

  printf "\r%-70s\r" " "   # clear progress line

  # ── Sort by Composite Score (descending) ─────────────────────────────────────
  SORTED_RESULTS=()
  for key in "${SERVER_KEYS[@]}"; do
    IFS='|' read -r avg med jitter rel <<< "${RESULTS_RAW[$key]}"
    local sc
    sc=$(composite_score "$avg" "$med" "$jitter" "$rel")
    SORTED_RESULTS+=("${key}|${sc}|${avg}|${med}|${jitter}|${rel}")
  done

  # Sort descending by score (field 2)
  IFS=$'\n' SORTED_RESULTS=($(printf '%s\n' "${SORTED_RESULTS[@]}" \
    | sort -t'|' -k2 -rn))

  # ── Output ───────────────────────────────────────────────────────────────────
  print_results
  print_winner

  # Apply flag
  if [[ "${1:-}" == "--apply" ]]; then
    IFS='|' read -r winner_key _ _ _ _ _ <<< "${SORTED_RESULTS[0]}"
    apply_dns "${DNS_IPS[$winner_key]}"
  fi
}

main "${@:-}"
